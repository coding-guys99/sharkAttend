create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  employee_no text not null unique check (employee_no ~ '^[0-9]+$'),
  name text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  work_date date not null,
  clock_in timestamptz,
  clock_out timestamptz,
  created_at timestamptz not null default now(),
  constraint attendance_order check (clock_out is null or (clock_in is not null and clock_out >= clock_in)),
  constraint attendance_one_day unique (user_id, work_date)
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
