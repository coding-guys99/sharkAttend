create or replace function public.clock_attendance(p_action text)
returns public.attendance_records
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_now timestamptz := now();
  v_work_date date := (v_now at time zone 'Asia/Taipei')::date;
  v_row public.attendance_records;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;
  if p_action not in ('in', 'out') then raise exception 'Invalid action'; end if;
  if p_action = 'in' then
    insert into public.attendance_records(user_id, work_date, clock_in)
    values (v_uid, v_work_date, v_now)
    on conflict (user_id, work_date) do nothing
    returning * into v_row;
    if v_row.id is null then raise exception 'Already clocked in today'; end if;
  else
    update public.attendance_records set clock_out = v_now
    where user_id = v_uid and work_date = v_work_date and clock_in is not null and clock_out is null
    returning * into v_row;
    if v_row.id is null then raise exception 'No open clock-in found today'; end if;
  end if;
  return v_row;
end;
$$;
revoke execute on function public.clock_attendance(text) from public, anon;
grant execute on function public.clock_attendance(text) to authenticated;
