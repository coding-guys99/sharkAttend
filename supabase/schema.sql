create or replace function public.clock_attendance(p_action text) returns public.attendance_records language plpgsql security definer set search_path='' as $$
declare v_uid uuid:=auth.uid();v_now timestamptz:=now();v_work_date date:=(v_now at time zone 'Asia/Taipei')::date;v_row public.attendance_records;
begin
 if v_uid is null then raise exception 'Not authenticated'; end if;
 if p_action not in ('in','out') then raise exception 'Invalid action'; end if;
 if p_action='in' then insert into public.attendance_records(user_id,work_date,clock_in) values(v_uid,v_work_date,v_now) on conflict(user_id,work_date) do nothing returning * into v_row;if v_row.id is null then raise exception 'Already clocked in today'; end if;
 else update public.attendance_records set clock_out=v_now where user_id=v_uid and work_date=v_work_date and clock_in is not null and clock_out is null returning * into v_row;if v_row.id is null then raise exception 'No open clock-in found today'; end if;end if;
 return v_row;
end;$$;
revoke execute on function public.clock_attendance(text) from public,anon;
grant execute on function public.clock_attendance(text) to authenticated;

create or replace function public.update_attendance_settings(p_start time,p_end time,p_grace integer) returns void language plpgsql security definer set search_path='' as $$
begin if auth.uid() is null or not private.is_admin() then raise exception 'Forbidden';end if;update public.attendance_settings set work_start=p_start,work_end=p_end,late_grace_minutes=p_grace,updated_at=now() where id=1;end;$$;
revoke execute on function public.update_attendance_settings(time,time,integer) from public,anon;
grant execute on function public.update_attendance_settings(time,time,integer) to authenticated;
create or replace function public.review_leave_request(p_id bigint,p_status text,p_note text default null) returns void language plpgsql security definer set search_path='' as $$
begin if auth.uid() is null or not private.is_admin() then raise exception 'Forbidden';end if;if p_status not in ('approved','rejected') then raise exception 'Invalid status';end if;update public.leave_requests set status=p_status,reviewer_id=auth.uid(),reviewed_at=now(),review_note=p_note where id=p_id and status='pending';if not found then raise exception 'Request not found or already reviewed';end if;end;$$;
revoke execute on function public.review_leave_request(bigint,text,text) from public,anon;
grant execute on function public.review_leave_request(bigint,text,text) to authenticated;
create or replace function public.review_correction_request(p_id bigint,p_status text,p_note text default null) returns void language plpgsql security definer set search_path='' as $$
declare r public.correction_requests;existing public.attendance_records;begin if auth.uid() is null or not private.is_admin() then raise exception 'Forbidden';end if;if p_status not in ('approved','rejected') then raise exception 'Invalid status';end if;select * into r from public.correction_requests where id=p_id and status='pending' for update;if r.id is null then raise exception 'Request not found or already reviewed';end if;if p_status='approved' then select * into existing from public.attendance_records where user_id=r.user_id and work_date=r.work_date;if existing.id is null then insert into public.attendance_records(user_id,work_date,clock_in,clock_out) values(r.user_id,r.work_date,r.requested_clock_in,r.requested_clock_out);else update public.attendance_records set clock_in=coalesce(r.requested_clock_in,clock_in),clock_out=coalesce(r.requested_clock_out,clock_out) where id=existing.id;end if;end if;update public.correction_requests set status=p_status,reviewer_id=auth.uid(),reviewed_at=now(),review_note=p_note where id=p_id;end;$$;
revoke execute on function public.review_correction_request(bigint,text,text) from public,anon;
grant execute on function public.review_correction_request(bigint,text,text) to authenticated;
