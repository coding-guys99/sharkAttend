-- sharkAttend production schema
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  employee_no text not null unique check (employee_no ~ '^[0-9]+$'),
  name text not null,
  role text not null default 'employee' check (role in ('employee','admin')),
  created_at timestamptz not null default now()
);
create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  work_date date not null,
  clock_in timestamptz,
  clock_out timestamptz,
  created_at timestamptz not null default now(),
  constraint attendance_order check (clock_out is null or (clock_in is not null and clock_out >= clock_in)),
  constraint attendance_one_day unique (user_id, work_date)
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  category text not null default 'general' check (category in ('general','attendance','holiday','event','important','system')),
  created_by uuid references auth.users(id) on delete set null,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create table if not exists public.employee_permissions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  can_manage_employees boolean not null default false,
  can_manage_permissions boolean not null default false,
  can_reset_passwords boolean not null default false,
  can_manage_announcements boolean not null default false,
  can_manage_attendance boolean not null default false,
  updated_at timestamptz not null default now()
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  title text not null,
  body text not null,
  kind text not null default 'general' check (kind in ('general','attendance','announcement','important','system')),
  created_at timestamptz not null default now(),
  expires_at timestamptz
);
create table if not exists public.attendance_settings (
  id integer primary key default 1 check (id=1),
  work_start time not null default '09:00',
  work_end time not null default '18:00',
  late_grace_minutes integer not null default 0 check (late_grace_minutes between 0 and 180),
  updated_at timestamptz not null default now()
);
insert into public.attendance_settings(id) values(1) on conflict(id) do nothing;
create table if not exists public.employee_schedules (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  work_date date not null,
  start_time time,
  end_time time,
  is_workday boolean not null default true,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id,work_date),
  check ((is_workday=false) or (start_time is not null and end_time is not null))
);
create table if not exists public.leave_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  leave_type text not null check (leave_type in ('annual','sick','personal','unpaid')),
  start_date date not null,
  end_date date not null,
  reason text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewer_id uuid references auth.users(id),
  reviewed_at timestamptz,
  review_note text,
  created_at timestamptz not null default now(),
  check (end_date>=start_date)
);
create table if not exists public.correction_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  work_date date not null,
  requested_clock_in timestamptz,
  requested_clock_out timestamptz,
  reason text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewer_id uuid references auth.users(id),
  reviewed_at timestamptz,
  review_note text,
  created_at timestamptz not null default now(),
  check (requested_clock_in is not null or requested_clock_out is not null),
  check (requested_clock_out is null or requested_clock_in is null or requested_clock_out>=requested_clock_in)
);

create schema if not exists private;
create or replace function private.is_admin() returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles where user_id=auth.uid() and role='admin');
$$;
revoke all on function private.is_admin() from public,anon;
grant execute on function private.is_admin() to authenticated;

